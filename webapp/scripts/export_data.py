"""Train SparseTSF (seed 2023) for each horizon and export everything the web demo needs
into webapp/data/model_data.js (a plain JS file, so index.html works from file:// with no server).

Exported:
  * trained weights (conv kernel + shared linear) for H = 96, 192, 336, 720
  * the standardized ETTh1 test region (with its 720-step look-back prefix), all 7 channels
  * a Python reference forecast for window 0 of each horizon (the page checks its JS math against it)
  * reproduction results (5 seeds) from results/*.json and the paper's reported numbers

Run from the project root:  .venv/bin/python webapp/scripts/export_data.py
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd
import torch

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "sparsetsf"))

from data import MONTH, ETTh1Windows  # noqa: E402
from train import run                  # noqa: E402

SEQ_LEN, PERIOD = 720, 24
HORIZONS = [96, 192, 336, 720]
PAPER = {  # paper Table 2 (SparseTSF) and Table 5 (Linear), ETTh1 MSE
    "sparsetsf_mse": {"96": 0.359, "192": 0.397, "336": 0.404, "720": 0.417},
    "sparsetsf_std": {"96": 0.006, "192": 0.002, "336": 0.001, "720": 0.001},
    "linear_mse": {"96": 0.371, "192": 0.460, "336": 0.417, "720": 0.424},
}


def train_args():
    return argparse.Namespace(seq_len=SEQ_LEN, period=PERIOD, batch_size=256, lr=0.02,
                              epochs=30, patience=5)


def summarize(path):
    if not os.path.exists(path):
        return None
    rows = json.load(open(path))
    out = {}
    for h in HORIZONS:
        rs = [r for r in rows if r["horizon"] == h]
        if rs:
            out[str(h)] = {k: [round(float(np.mean([r[k] for r in rs])), 4),
                               round(float(np.std([r[k] for r in rs])), 4)]
                           for k in ("mse_paper", "mae_paper", "mse_full", "mae_full")}
            out[str(h)]["params"] = rs[0]["params"]
    return out


def main():
    torch.set_num_threads(8)
    csv = os.path.join(ROOT, "data", "ETTh1.csv")
    channels = list(pd.read_csv(csv, nrows=1).columns[1:])
    test = ETTh1Windows(csv, "test", SEQ_LEN, 96).x.numpy()      # (3600, 7) standardized
    start = pd.read_csv(csv)["date"].iloc[16 * MONTH - SEQ_LEN]

    models = {}
    for h in HORIZONS:
        # re-train with the paper's protocol (seed 2023) and keep the weights
        res, m = run("sparsetsf", h, 2023, train_args(), return_model=True)
        m.eval()

        with torch.no_grad():
            x0 = torch.tensor(test[:SEQ_LEN], dtype=torch.float32).unsqueeze(0)
            ref = m(x0)[0].numpy()                                 # (H, 7)
        models[str(h)] = {
            "conv": [round(float(v), 6) for v in m.agg.weight.detach().view(-1)],
            "linear": [[round(float(v), 6) for v in row] for row in m.linear.weight.detach()],
            "params": res["params"],
            "test_mse": round(res["mse_full"], 4), "test_mae": round(res["mae_full"], 4),
            "ref_window0": [[round(float(v), 5) for v in row] for row in ref.T],  # (7, H)
        }
        print(f"H={h}: params={res['params']} test MSE={res['mse_full']:.4f}")

    data = {
        "meta": {"dataset": "ETTh1", "seq_len": SEQ_LEN, "period": PERIOD,
                 "channels": channels, "test_start": start, "freq_hours": 1,
                 "note": "values are z-score standardized with training-split statistics"},
        "series": [[round(float(v), 4) for v in test[:, c]] for c in range(test.shape[1])],
        "models": models,
        "results": {"sparsetsf": summarize(os.path.join(ROOT, "results", "sparsetsf_etth1.json")),
                    "linear": summarize(os.path.join(ROOT, "results", "linear_etth1.json")),
                    "paper": PAPER},
    }
    out = os.path.join(ROOT, "webapp", "data", "model_data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("// Generated by webapp/scripts/export_data.py - do not edit by hand.\n")
        f.write("window.SPARSETSF_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print("wrote", out, f"({os.path.getsize(out) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
